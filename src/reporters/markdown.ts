import type { AnalysisResult } from "../types.js";

const STATUS_ICON = {
  aligned: "✅",
  undocumented: "❌",
  stale: "⚠️",
  "provider-only": "⚠️"
} as const;

export function formatMarkdown(result: AnalysisResult): string {
  const lines = [
    "# EnvTrail report",
    "",
    `**Configuration health: ${result.summary.score}/100** · ${result.summary.variables} variables across ${result.summary.filesScanned} files`,
    "",
    "| Variable | Code | Docs | Deploy | Status |",
    "| --- | :---: | :---: | :---: | --- |"
  ];

  for (const variable of result.variables) {
    lines.push(
      `| \`${escapeMarkdown(variable.name)}\` | ${mark(variable.consumers.length)} | ${mark(variable.documentation.length)} | ${mark(variable.providers.length)} | ${STATUS_ICON[variable.status]} ${variable.status} |`
    );
  }

  lines.push("", "## Findings", "");
  if (result.issues.length === 0) {
    lines.push("No findings. Your environment-variable trail is aligned.");
  } else {
    for (const issue of result.issues) {
      const location = issue.locations[0];
      lines.push(
        `- **${issue.severity.toUpperCase()} ${issue.ruleId}** — ${issue.message}${location ? ` (\`${location.file}:${location.line}\`)` : ""}`,
        `  - Fix: ${issue.hint}`
      );
    }
  }

  lines.push(
    "",
    `_<sub>Generated by EnvTrail ${result.tool.version}. Values are never included in reports.</sub>_`,
    ""
  );
  return lines.join("\n");
}

function mark(count: number): string {
  return count > 0 ? `● ${count}` : "—";
}

function escapeMarkdown(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll("`", "\\`");
}
